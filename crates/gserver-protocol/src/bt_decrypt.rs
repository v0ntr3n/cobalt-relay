/// Complete 16-slot `off_CC01A0` key table from `libcocos2dlua.so`.
pub const BT_KEY_TABLES: [&[u8]; 16] = [
    &KEY_00, &KEY_01, &KEY_02, &KEY_03, &KEY_04, &KEY_05, &KEY_06, &KEY_07,
    &KEY_08, &KEY_09, &KEY_0A, &KEY_0B, &KEY_0C, &KEY_0D, &KEY_0E, &KEY_0F,
];

/// Returns `true` if `data` carries the `0xFEFEFEFE` 4-byte magic prefix.
pub fn has_bt_magic(data: &[u8]) -> bool {
    data.len() >= 4 && u32::from_le_bytes([data[0], data[1], data[2], data[3]]) == BT_DECRYPT_MAGIC
}

/// Decrypts an GServer asset buffer if it starts with `0xFEFEFEFE`, or returns a copy of
/// plaintext buffers unchanged. Rejects truncated or malformed `0xFEFEFEFE` headers.
pub fn bt_decrypt_or_passthrough(data: &[u8]) -> Result<Vec<u8>, BtDecryptError> {
    if !has_bt_magic(data) {
        return Ok(data.to_vec());
    }
    bt_decrypt(data)
}

/// Decrypts an encrypted `0xFEFEFEFE` asset buffer and strips its 32-byte header.
pub fn bt_decrypt(data: &[u8]) -> Result<Vec<u8>, BtDecryptError> {
    if data.len() < BT_DECRYPT_HEADER_SIZE {
        return Err(BtDecryptError::TruncatedHeader { len: data.len() });
    }
    let magic = u32::from_le_bytes([data[0], data[1], data[2], data[3]]);
    if magic != BT_DECRYPT_MAGIC {
        return Err(BtDecryptError::TruncatedHeader { len: data.len() });
    }

    let header_payload_size = u32::from_le_bytes([data[4], data[5], data[6], data[7]]);
    let algo_index = data[8];
    let key_index = data[9];
    let actual_payload_size = data.len() - BT_DECRYPT_HEADER_SIZE;

    if header_payload_size as usize != actual_payload_size {
        return Err(BtDecryptError::PayloadLengthMismatch {
            header_payload_size,
            actual_payload_size,
        });
    }
    if algo_index != 0 && algo_index != 1 {
        return Err(BtDecryptError::UnsupportedAlgoIndex(algo_index));
    }
    if key_index > 15 {
        return Err(BtDecryptError::InvalidKeyIndex(key_index));
    }

    let key = BT_KEY_TABLES[key_index as usize];
    let key_len = key.len();
    let offset = actual_payload_size % key_len;

    let mut payload = data[BT_DECRYPT_HEADER_SIZE..].to_vec();
    let mut i = 0usize;
    while i < payload.len() {
        payload[i] ^= key[(i + offset) % key_len];
        i += 2;
    }
    Ok(payload)
}

/// Encrypts `plaintext` with the symmetric `bt_decrypt` XOR algorithm and prepends the 32-byte header.
pub fn bt_encrypt(plaintext: &[u8], key_index: u8) -> Result<Vec<u8>, BtDecryptError> {
    if key_index > 15 {
        return Err(BtDecryptError::InvalidKeyIndex(key_index));
    }
    let payload_len = plaintext.len();
    let payload_u32 = u32::try_from(payload_len).map_err(|_| BtDecryptError::PayloadLengthMismatch {
        header_payload_size: u32::MAX,
        actual_payload_size: payload_len,
    })?;

    let mut out = Vec::with_capacity(BT_DECRYPT_HEADER_SIZE + payload_len);
    out.extend_from_slice(&BT_DECRYPT_MAGIC.to_le_bytes());
    out.extend_from_slice(&payload_u32.to_le_bytes());
    out.push(1u8); // mode = 1 (decrypt_basic)
    out.push(key_index);
    out.extend_from_slice(&[0u8; 22]);
    out.extend_from_slice(plaintext);

    let key = BT_KEY_TABLES[key_index as usize];
    let key_len = key.len();
    let offset = payload_len % key_len;
    let payload_slice = &mut out[BT_DECRYPT_HEADER_SIZE..];
    let mut i = 0usize;
    while i < payload_slice.len() {
        payload_slice[i] ^= key[(i + offset) % key_len];
        i += 2;
    }
    Ok(out)
}
